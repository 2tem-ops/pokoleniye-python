# Камень, ножницы, бумага, ящерица, Спок

rules = {
    "камень": ("ящерица", "ножницы"),
    "ножницы": ("бумага", "ящерица"),
    "бумага": ("камень", "Спок"),
    "ящерица": ("Спок", "бумага"),
    "Спок": ("камень", "ножницы")
}

p1, p2 = input(), input()
if p2 in rules[p1]:
    print("Тимур")
elif p1 in rules[p2]:
    print("Руслан")
else:
    print("ничья")