# Список продуктов

def print_product_list(product_list):
    emoji = {
    'яблоко': '🍎', 'хлеб': '🍞', 'конфеты': '🍬', 'лимон': '🍋',
    'морковь': '🥕', 'огурец': '🥒', 'помидор': '🍅', 'яйцо': '🥚',
    'чеснок': '🧄', 'авокадо': '🥑', 'спички': '🥢', 'соль': '🧂',
    'филе говядины': '🥩', 'киви': '🥝', 'лук': '🧅', 'сыр': '🧀',
    }
    for product in set(product_list):
        print(f"{emoji.get(product, product)}: {product_list.count(product)}")


product_list = [
    'спички', 'соль', 'огурец', 'лук',
    'конфеты', 'сыр', 'филе говядины',
    'оливковое масло', 'филе горбуши',
    'яблоко', 'киви', 'сыр', 'киви',
    'лук', 'конфеты', 'лимон', 'лимон',
]
print_product_list(product_list)